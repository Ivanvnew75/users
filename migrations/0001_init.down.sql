-- Откат 0001.
--
-- Down-миграции пишут не потому, что их часто применяют в проде (там откат
-- схемы почти всегда опаснее, чем накат исправления), а потому что они
-- нужны в разработке и в CI: поднять базу, накатить, откатить, накатить снова —
-- это проверка, что миграция вообще воспроизводима.
--
-- Порядок обратный накату: сначала таблица со внешним ключом, потом та,
-- на которую он ссылается.
DROP TABLE IF EXISTS mood_answers;
DROP TABLE IF EXISTS users;
