-- 0002 — возможность отписаться от рассылки.
--
-- БЕЗОПАСНОСТЬ ЭТОЙ МИГРАЦИИ (то, что обязательно проверяют на проде):
--
-- ADD COLUMN ... NOT NULL DEFAULT в PostgreSQL 11+ выполняется МГНОВЕННО:
-- значение по умолчанию пишется в метаданные таблицы, существующие строки
-- не переписываются. До 11-й версии такая же команда переписывала всю
-- таблицу под ACCESS EXCLUSIVE-блокировкой — на большой таблице это
-- многоминутная остановка сервиса.
--
-- Отсюда правило: «безопасность» миграции зависит от версии движка,
-- и это ещё одна причина для Фактора 10 — тестировать миграции на той же
-- версии, что в проде.
ALTER TABLE users
    ADD COLUMN IF NOT EXISTS notify_enabled BOOLEAN NOT NULL DEFAULT true;

-- Частичный индекс: он покрывает только строки, которые реально нужны
-- рассылке. Такой индекс меньше обычного и не растёт от отписавшихся.
CREATE INDEX IF NOT EXISTS users_notify_idx
    ON users (id) WHERE notify_enabled AND telegram_id IS NOT NULL;
