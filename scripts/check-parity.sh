#!/usr/bin/env bash
# Проверяет, что версия backing service одинакова везде, где она упомянута.
#
# ЗАЧЕМ ЭТОТ СКРИПТ СУЩЕСТВУЕТ
#
# Фактор 10 нарушается не одномоментно, а дрейфом. Кто-то поднял версию
# Postgres в кластере, забыл про compose — и через месяц разработчик
# отлаживает на 15-й версии то, что в проде работает на 17-й. Никто
# не принимал такого решения, оно просто накопилось.
#
# Дрейф лечится только автоматической проверкой: договорённость
# «не забывать обновлять в трёх местах» не работает никогда.
#
# Проверяются источники внутри репозитория (их видит CI):
#   * compose.yaml                    — локальная разработка
#   * .github/workflows/ci.yml        — service container для тестов
# И дополнительно, если каталог доступен локально:
#   * ../infra/10-postgres.yaml       — кластер
#
# Ограничение, о котором стоит знать: манифесты кластера лежат вне этого
# репозитория, поэтому в CI они не проверяются. В настоящем проекте
# это решается либо отдельным репозиторием инфраструктуры, который
# подключают в CI через checkout, либо тем, что версия объявлена
# один раз в одном месте и подставляется шаблоном.
set -euo pipefail

cd "$(dirname "$0")/.."

fail=0
declare -A found

extract() {
  # $1 — файл, $2 — человекочитаемое имя источника
  local file="$1" label="$2"
  [[ -f "$file" ]] || return 0
  local ver
  ver="$(grep -oE 'postgres:[0-9]+(\.[0-9]+)?(-[a-z0-9]+)?' "$file" | head -1 || true)"
  if [[ -n "$ver" ]]; then
    found["$label"]="$ver"
  fi
}

extract "compose.yaml"                 "compose (локальная разработка)"
extract ".github/workflows/ci.yml"     "CI (тесты)"
extract "../infra/10-postgres.yaml"    "кластер"

if [[ ${#found[@]} -eq 0 ]]; then
  echo "Не найдено ни одного упоминания образа postgres — проверять нечего."
  exit 1
fi

echo "Версии PostgreSQL по источникам:"
for label in "${!found[@]}"; do
  printf '  %-32s %s\n' "$label" "${found[$label]}"
done

# Уникальные значения
uniq_count="$(printf '%s\n' "${found[@]}" | sort -u | wc -l)"
if [[ "$uniq_count" -ne 1 ]]; then
  echo
  echo "РАСХОЖДЕНИЕ: версии не совпадают."
  echo "Это Фактор 10: разработка и прод обязаны идти на одном движке."
  fail=1
else
  echo
  echo "OK: версия одна во всех источниках."
fi

exit "$fail"
